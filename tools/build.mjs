#!/usr/bin/env node
/**
 * Assemble the client half into one file the DSH client module loader can take.
 *
 * The pet is authored as ordinary ES modules (drawing, life state, the in-page
 * host, the settings page). The loader wants a single `client.js` that calls
 * `window.__ModuleLoader__.load({ id, factory })`, so this script wraps each
 * module in an IIFE whose parameters are its imports — no bundler, no
 * dependencies, and the sources stay readable.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PKG = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
// 鲸鱼的经典蓝切图（WebP）直接写进 client.js：桌面版页面是 dsh-app:// 协议，
// 请求不到 Host 上的路由，图片只能跟着代码走。另两种配色在页面上现场换色。
import { readdirSync } from "node:fs";
const SPRITE_DIR = "sprites";

// Dependency order: a module only ever imports modules above it.
const MODULES = [
  { id: "places", file: "lib/pet/places.js" },
  { id: "spritesMeta", file: "lib/pet/sprites-meta.js" },
  { id: "sprite", file: "lib/pet/sprite.js" },
  { id: "art", file: "lib/pet/art.js" },
  { id: "state", file: "lib/pet/state.js" },
  { id: "store", file: "lib/store.js" },
  { id: "host", file: "lib/host.js" },
  { id: "app", file: "lib/app.js" },
  { id: "markup", file: "lib/markup.js" },
  { id: "engine", file: "lib/engine.js" },
  { id: "layer", file: "lib/layer.js" },
  { id: "settings", file: "lib/settings.js" },
  { id: "main", file: "lib/main.js" },
];

const byBasename = new Map(MODULES.map((m) => [m.file.split("/").pop(), m.id]));
const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*["']([^"']+)["'];?\s*$/;

function transform(entry) {
  const source = readFileSync(join(ROOT, entry.file), "utf8").split("\n");
  const imports = [];
  const exported = [];
  const body = [];

  for (const line of source) {
    const imp = line.match(IMPORT_RE);
    if (imp) {
      const names = imp[1].split(",").map((part) => part.trim()).filter(Boolean);
      const from = imp[2];
      const id = from === "runtime" ? "runtime" : byBasename.get(from.split("/").pop());
      if (!id) throw new Error(`${entry.file}: cannot resolve import "${from}"`);
      imports.push({ id, names });
      continue;
    }
    const decl = line.match(/^export\s+(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/);
    if (decl) {
      exported.push(decl[1]);
      body.push(line.replace(/^export\s+/, ""));
      continue;
    }
    if (/^export\s*\{/.test(line)) {
      const inner = line.slice(line.indexOf("{") + 1, line.indexOf("}"));
      for (const part of inner.split(",").map((p) => p.trim()).filter(Boolean)) {
        const [name, alias] = part.split(/\s+as\s+/).map((p) => p.trim());
        exported.push(alias ? `${alias}: ${name}` : name);
      }
      continue;
    }
    body.push(line);
  }

  const patterns = imports.map(({ id, names }) => {
    const entries = names.map((n) => {
      const [orig, alias] = n.split(/\s+as\s+/).map((p) => p.trim());
      return alias ? `${orig}: ${alias}` : orig;
    });
    return { pattern: `{ ${entries.join(", ")} }`, value: id === "runtime" ? "RUNTIME" : `M.${id}` };
  });

  return {
    id: entry.id,
    imports,
    source: body.join("\n").trim(),
    exported: exported.join(", "),
    call: patterns.length
      ? `((${patterns.map((p) => p.pattern).join(", ")}) => {\nBODY\n\nreturn { ${exported} };\n})(${patterns.map((p) => p.value).join(", ")})`
      : `(() => {\nBODY\n\nreturn { ${exported} };\n})()`,
  };
}

const modules = MODULES.map(transform);
const known = new Set(["runtime", ...modules.map((m) => m.id)]);
for (const m of modules) {
  for (const imp of m.imports) if (!known.has(imp.id)) throw new Error(`${m.id} imports unknown module ${imp.id}`);
}

const chunks = modules.map((m) => {
  const body = m.call.replace("BODY", () => m.source);
  return `/* --- ${m.id} --- */\nM.${m.id} = ${body};`;
});

const css = readFileSync(join(ROOT, "lib/pet.css"), "utf8");

function spriteData() {
  const out = {};
  for (const f of readdirSync(join(ROOT, SPRITE_DIR)).sort()) {
    const m = /^whale-([a-z]+)\.webp$/.exec(f);
    if (m) out[m[1]] = "data:image/webp;base64," + readFileSync(join(ROOT, SPRITE_DIR, f)).toString("base64");
  }
  return out;
}

const out = `/* generated by tools/build.mjs — edit lib/ instead */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PKG.name)},
  factory(require) {
    const React = require("react");
    const RUNTIME = {
      React,
      css: ${JSON.stringify(css)},
      spriteData: ${JSON.stringify(spriteData())},
    };
    const M = {};

${chunks.join("\n\n")}

    return M.main.plugin;
  },
});
`;

writeFileSync(join(ROOT, "client.js"), out);
console.log(`client.js written: ${(out.length / 1024).toFixed(1)} KiB, ${modules.length} modules`);
